// Copies the video formats, their briefs, the tool names and the card drawings from the
// Scale Video Toolkit site page into renderer/data/formats.js and renderer/lib/art.js.
// Usage: node scripts/import-toolkit.js <path to the toolkit site's index.html>
const fs = require('node:fs');
const path = require('node:path');

const src = process.argv[2];
if (!src) { console.error('Usage: node scripts/import-toolkit.js <site index.html>'); process.exit(1); }
const s = fs.readFileSync(src, 'utf8');
const root = path.join(__dirname, '..');

// Reads `var NAME = <literal>;` from the page by bracket matching.
function grab(name) {
  const i = s.indexOf('var ' + name + ' =');
  if (i < 0) throw new Error('Not found: ' + name);
  let j = s.indexOf('=', i) + 1, depth = 0, k = j, started = false;
  for (; k < s.length; k++) {
    const ch = s[k];
    if (ch === '[' || ch === '{') { depth++; started = true; }
    else if (ch === ']' || ch === '}') { depth--; if (started && depth === 0) { k++; break; } }
  }
  return (0, eval)('(' + s.slice(j, k) + ')');
}

const FORMATS = grab('FORMATS'), BRIEFS = grab('BRIEFS'), CATS = grab('CATS'), TOOLS = grab('TOOLS');
const formats = FORMATS.map(f => ({
  id: f.id, name: f.name, art: f.art, cats: f.cats, shape: f.shape, blurb: f.blurb,
  give: f.give, get: f.get, tools: f.tools, ask: f.ask, brief: BRIEFS[f.id] || ''
}));
const tools = Object.fromEntries(Object.entries(TOOLS).map(([id, t]) => [id, { name: t.name, kind: t.kind, does: t.does }]));
const cats = CATS.map(c => ({ id: c.id, name: c.name, pastel: c.pastel, head: c.head, sub: c.sub }));
fs.writeFileSync(path.join(root, 'renderer/data/formats.js'),
  '// Generated by scripts/import-toolkit.js from the Scale Video Toolkit site. Do not edit by hand.\n' +
  '// Each [blank] in a brief becomes one interview question before the prompt goes to the agent.\n' +
  'window.SVE_CATEGORIES = ' + JSON.stringify(cats, null, 2) + ';\n\n' +
  'window.SVE_TOOLS = ' + JSON.stringify(tools, null, 2) + ';\n\n' +
  'window.SVE_FORMATS = ' + JSON.stringify(formats, null, 2) + ';\n');

// The drawings: the helper functions through the art() function, copied as they are.
const start = s.indexOf('  function seq(n, f)');
const endMarker = "function art(name) {";
const end = s.indexOf('\n', s.indexOf(endMarker));
if (start < 0 || end < 0) throw new Error('Drawing code not found');
fs.writeFileSync(path.join(root, 'renderer/lib/art.js'),
  '// Generated by scripts/import-toolkit.js from the Scale Video Toolkit site. Do not edit by hand.\n' +
  '// Card drawings: a 320 x 180 frame drawn in the card ink (currentColor), with the card pastel\n' +
  '// (--tile-bg) as the cut-out colour and coral as the one accent.\n' +
  '(function () {\n' + s.slice(start, end + 1) + '  window.SVE_ART = function (name) { return ART[name] ? art(name) : art(\'film\'); };\n})();\n');
console.log(`${formats.length} formats, ${cats.length} categories, ${Object.keys(tools).length} tools, drawings copied.`);
