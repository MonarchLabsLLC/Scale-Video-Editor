'use strict';
// Builds the Viral Videos data for the editor from scripts/viral/viral.json.
// Run: node scripts/viral/build.js
const fs = require('node:fs');
const path = require('node:path');
const src = JSON.parse(fs.readFileSync(path.join(__dirname, 'viral.json'), 'utf8'));
const out = path.join(__dirname, '..', '..', 'renderer', 'data', 'viral.js');
fs.writeFileSync(out, '// Generated by scripts/viral/build.js from scripts/viral/viral.json. Do not edit by hand.\nwindow.SVE_VIRAL = ' + JSON.stringify(src, null, 2) + ';\n');
console.log('wrote', path.relative(process.cwd(), out), src.formats.length, 'formats');
